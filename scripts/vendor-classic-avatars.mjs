// Rebuild the embedded, unmodified classic QQ bitmaps from a pinned source.
// Artwork is owned by Tencent; see NOTICE.md before redistributing.
import { writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'

const revision = '2dce4e47beb9b55494c492a6cf6e2c01eb77dbe3'
const base = `https://raw.githubusercontent.com/mengkunsoft/QQ2006/${revision}/img/avatar/`
const images = Array(100)
let cursor = 0
await Promise.all(Array.from({ length: 5 }, async () => {
  while (cursor < images.length) {
    const index = cursor++
    const response = await fetch(`${base}${index + 1}.png`, { signal: AbortSignal.timeout(30000) })
    if (!response.ok) throw new Error(`Avatar ${index + 1}: HTTP ${response.status}`)
    const bytes = Buffer.from(await response.arrayBuffer())
    if (bytes.length > 100000 || bytes.subarray(0, 8).toString('hex') !== '89504e470d0a1a0a') {
      throw new Error(`Avatar ${index + 1}: invalid PNG`)
    }
    images[index] = `data:image/png;base64,${bytes.toString('base64')}`
  }
}))
const output = `// Generated by scripts/vendor-classic-avatars.mjs. Artwork: Tencent; see NOTICE.md.\n// Source revision: ${revision}. Original PNG pixels are unchanged.\nexport const CLASSIC_AVATAR_IMAGES: readonly string[] = ${JSON.stringify(images, null, 2)}\n`
await writeFile(new URL('../src/client/classic-avatar-data.ts', import.meta.url), output)
console.log(JSON.stringify({ count: images.length, sourceRevision: revision, bytes: Buffer.byteLength(output), sha256: createHash('sha256').update(output).digest('hex') }))
